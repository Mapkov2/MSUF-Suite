"""Copy Enhance QoL's WoW Forever spell groups, racials and consumables into the cooldown manager.

Usage (from the repo root):
  python tools/import_eqol_forever_presets.py <Enhance QoL folder> [--check]

<Enhance QoL folder> holds Enhance QoL's addon folders: its repository root or
the Forever client's Interface/AddOns. R41z0r (Enhance QoL) reviews this data
against the Forever client data and permitted the Suite to use it (2026-11-12).
This tool only copies what the Suite has a place for:
  * EnhanceQoLCooldownPanels/CooldownPanels_SpellGroupPresets_Camelot.lua: the
    Defensives bar's default (PERSONAL_DEFENSIVES) and the picker groups
    (KICKS, HARD_CC, MOVEMENT, BATTLE_REZ, DISPELS, OFFENSIVE_COOLDOWNS). Per
    class, in Enhance QoL's order, each member's cast ID (its first rank:
    RankData.lua covers the other ranks), then the member's aliases that are
    not ranks of that spell;
  * EnhanceQoLCooldownPanels/CooldownPanels_Camelot.lua: the active racials
    (foreverRacialSpellFamilies), every variant of each;
  * EnhanceQoL/Modules/Food/ConsumableData_Camelot.lua: mana potions and
    bandages, weakest first (the Suite's families show the strongest one the
    bags hold);
  * EnhanceQoLCooldownPanels/CooldownPanels_AuraPresetData_Camelot.lua: the
    other potions (foreverPotionItemIDs without the healing, mana and
    rejuvenation potions, which have their own families).
It writes MSUF_Suite_CooldownManager/ForeverPresets.lua; --check compares
instead of writing (exit 1 on a difference).
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "MSUF_Suite_CooldownManager" / "ForeverPresets.lua"
RANKS = ROOT / "MSUF_Suite_CooldownManager" / "RankData.lua"
GROUPS_FILE = "EnhanceQoLCooldownPanels/CooldownPanels_SpellGroupPresets_Camelot.lua"
PANELS_FILE = "EnhanceQoLCooldownPanels/CooldownPanels_Camelot.lua"
CONSUMABLES_FILE = "EnhanceQoL/Modules/Food/ConsumableData_Camelot.lua"
POTIONS_FILE = "EnhanceQoLCooldownPanels/CooldownPanels_AuraPresetData_Camelot.lua"
BUILD = re.compile(r"^-- Forever cast IDs, checked against the reviewed ([\d.]+) spell data", re.M)
GROUP = re.compile(r"^\s*([A-Z_]+) = \{\s*$")
MEMBER = re.compile(r"^\s*spell\((\d+), (\d+|nil)(?:, \{(.*)\})?\),\s*-- (.+?)\s*$")
ALIASES = re.compile(r"aliases = \{ ([\d, ]+) \}")
FAMILY = re.compile(r"^\s*\[(\d+)\] = \{ ([\d, ]+) \}", re.M)
RACIALS = re.compile(r"foreverRacialSpellFamilies = \{\n(.*?)\n\}", re.S)
RACIAL = re.compile(r"^\s*\{ ([\d, ]+) \},\s*-- (.+?)\s*$", re.M)
ITEM = re.compile(r"\{ id = (\d+), ([^}]*)\}")
FIELD = re.compile(r"(\w+) = (\"[^\"]*\"|[\w.]+)")
POTION_IDS = re.compile(r"foreverPotionItemIDs = \{ ([\d, ]+) \}")
POTION_NAME = re.compile(r"^\s*\[(\d+)\] = \{ \d+ \}, -- (.+?)\s*$", re.M)
# Enhance QoL group -> the Suite's preset name, in the Suite's order.
GROUPS = [("PERSONAL_DEFENSIVES", "defensives"), ("KICKS", "interrupts"), ("HARD_CC", "crowdcontrol"),
          ("MOVEMENT", "movement"), ("BATTLE_REZ", "battlerez"), ("DISPELS", "dispels"),
          ("OFFENSIVE_COOLDOWNS", "offensive")]
CLASSES = {1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest", 7: "Shaman", 8: "Mage", 9: "Warlock",
           11: "Druid"}
# Potions Enhance QoL lists without a name in its aura data (comments only).
POTION_NAMES = {5633: "Great Rage Potion", 13462: "Purification Potion"}
OWN_FAMILIES = ("healing_potion", "mana_potion", "healing_and_mana_potion")

HEADER = """local _, P = ...
local C = P.CDM
-- WoW Forever spell groups and consumables: the Defensives bar's default, the
-- picker's spell groups, and the racials, potions and bandages of the Potions
-- and racials bar.
-- Credits: R41z0r (Enhance QoL, https://www.curseforge.com/wow/addons/eqol)
-- built and maintains this data and allowed the Suite to use it. Copied from
-- his spell group presets (reviewed against the Forever spell data of build
-- {build}), his racial families and his Forever consumable data.
-- Generated by tools/import_eqol_forever_presets.py; do not edit by hand.
-- Spell groups per classID: cast IDs, first rank each (RankData.lua names the
-- other ranks), then another cast ID of the same ability where Enhance QoL
-- lists one. Racials: every race, every variant. Item lists run weakest first.
-- Presets.lua uses these on Forever only; Retail loads nothing here.
if not P.NS.Client.isForever then return end
C.FOREVER_PRESETS = {{
"""


def read(root, relative):
    path = Path(root) / relative
    if not path.is_file():
        raise ValueError(f"missing {relative} under {root}: point the tool at Enhance QoL's folder")
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def families():
    owner = {}
    for key, ranks in FAMILY.findall(RANKS.read_text(encoding="utf-8")):
        for rank in ranks.split(","):
            owner[int(rank)] = int(key)
    return owner


def parse_groups(text):
    build = BUILD.search(text)
    if not build:
        raise ValueError("no reviewed build line in " + GROUPS_FILE)
    wanted, groups, current = dict(GROUPS), {}, None
    for raw in text.splitlines():
        group = GROUP.match(raw)
        if group:
            current = groups.setdefault(group.group(1), []) if group.group(1) in wanted else None
            continue
        member = MEMBER.match(raw)
        if member and current is not None:
            spell, cls, options, name = int(member.group(1)), member.group(2), member.group(3) or "", member.group(4)
            aliases = ALIASES.search(options)
            current.append((spell, None if cls == "nil" else int(cls), name,
                            [int(x) for x in aliases.group(1).split(",")] if aliases else []))
    for source, _ in GROUPS:
        if not groups.get(source):
            raise ValueError("group " + source + " missing or empty")
    return build.group(1), groups


def parse_racials(text):
    block = RACIALS.search(text)
    if not block:
        raise ValueError("no foreverRacialSpellFamilies in " + PANELS_FILE)
    racials = [([int(x) for x in ids.split(",")], name) for ids, name in RACIAL.findall(block.group(1))]
    if not racials:
        raise ValueError("no racial families")
    return racials


def parse_items(text):
    items = []
    for item_id, body in ITEM.findall(text):
        fields = {key: value.strip('"') for key, value in FIELD.findall(body)}
        fields["id"] = int(item_id)
        items.append(fields)
    if not items:
        raise ValueError("no items in " + CONSUMABLES_FILE)
    return items


def weakest_first(items, resource):
    known = [float(i[resource]) for i in items if resource in i]
    low = min(known) if known else 0

    # An item without a recovery value sorts with the weakest; the family key
    # (its first item) is a listed one.
    def key(item):
        return (float(item.get(resource, low)), resource not in item, item["id"])
    return sorted(items, key=key)


def consumables(items, potion_text):
    mana = weakest_first([i for i in items if i.get("category") == "mana_potion"], "mana")
    bandages = weakest_first([i for i in items if i.get("category") == "bandage"], "health")
    own = {i["id"] for i in items if i.get("category") in OWN_FAMILIES}
    ids = POTION_IDS.search(potion_text)
    if not ids or not mana or not bandages:
        raise ValueError("Forever potion, mana potion or bandage list missing")
    names = {int(k): v for k, v in POTION_NAME.findall(potion_text)}
    names.update(POTION_NAMES)
    combat = [int(x) for x in ids.group(1).split(",") if int(x) not in own]
    return mana, bandages, [(i, names.get(i, "item %d" % i)) for i in combat]


def ids_of(member, owner):
    spell, _, _, aliases = member
    base = owner.get(spell, spell)
    out = [base]
    for alias in aliases:
        if owner.get(alias, alias) != base and alias not in out:
            out.append(alias)
    return out


def render_groups(groups, owner):
    lines = []
    for source, name in GROUPS:
        lines.append("    %s = {" % name)
        by_class = {}
        for member in groups[source]:
            if member[1] is None:
                raise ValueError(f"{source}: {member[2]} has no class")
            by_class.setdefault(member[1], []).append(member)
        for cls in sorted(by_class):
            lines.append("        [%d] = { -- %s" % (cls, CLASSES.get(cls, "class %d" % cls)))
            for member in by_class[cls]:
                lines.append("            %s, -- %s" % (", ".join(str(x) for x in ids_of(member, owner)), member[2]))
            lines.append("        },")
        lines.append("    },")
    return lines


def render_items(name, rows):
    return ["    %s = {" % name] + ["        %d, -- %s" % row for row in rows] + ["    },"]


def render(root):
    build, groups = parse_groups(read(root, GROUPS_FILE))
    racials = parse_racials(read(root, PANELS_FILE))
    mana, bandages, combat = consumables(parse_items(read(root, CONSUMABLES_FILE)), read(root, POTIONS_FILE))
    lines = render_groups(groups, families())
    lines.append("    racials = {")
    for ids, name in racials:
        lines.append("        %s, -- %s" % (", ".join(str(x) for x in ids), name))
    lines.append("    },")

    def level(item):
        return " (level %s)" % item["requiredLevel"] if item.get("requiredLevel", "0") != "0" else ""
    lines += render_items("manaPotions", [(i["id"], ("%s mana" % i["mana"] if "mana" in i else "mana potion")
                                           + level(i)) for i in mana])
    lines += render_items("combatPotions", combat)
    lines += render_items("bandages", [(i["id"], "%s health (First Aid %s)" % (i["health"], i.get("requiredSkillRank", "1")))
                                       for i in bandages])
    count = sum(len(groups[s]) for s, _ in GROUPS)
    summary = f"{count} spells, {len(racials)} racials, {len(mana) + len(combat) + len(bandages)} items, Forever build {build}"
    return HEADER.format(build=build) + "\n".join(lines) + "\n}\n", summary


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    text, summary = render(args[0])
    if "--check" in sys.argv:
        same = OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") == text
        print(("ok   " if same else "DIFF ") + f"{OUTPUT.name}: {summary}")
        return 0 if same else 1
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
