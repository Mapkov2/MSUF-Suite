local root = assert(arg[1])
local H = assert(loadfile(root .. "/tools/tests/suite_installer_harness.lua"))()
for _, forever in ipairs({ false, true }) do
    local Suite = H.Setup({ root = root, forever = forever })
    assert(Suite.Installer.Open())
    local w = MSUFSuiteInstallFrame
    w.next.scripts.OnClick()
    w.modernDark.scripts.OnClick()
    local p = w.layoutPreview
    assert(p.screenshot:IsShown() and not p.canvas:IsShown(), "Modern Dark has no real screenshot")
    assert(p.screenshot.art.texture == "Interface\\AddOns\\MSUF_Suite\\Media\\ModernDarkPreview.tga")
    assert(p.screenshot.art.texCoords[4] == 1152 / 2048, "padded backing leaked into the image")
    assert(math.abs(p.screenshot:GetWidth() / p.screenshot:GetHeight() - 2559 / 1439) < .0001)
    p.screenshot.scripts.OnClick()
    local zoom = p.screenshotZoom
    assert(zoom:IsShown() and zoom.art.texture == p.screenshot.art.texture)
    assert(zoom:GetWidth() <= UIParent:GetWidth() - 32 and zoom:GetHeight() <= UIParent:GetHeight() - 32)
    assert(UISpecialFrames[#UISpecialFrames] == "MSUFSuiteScreenshotFrame", "Escape cannot close the image")
    zoom.close.scripts.OnClick()
    assert(not zoom:IsShown())
    p.screenshotToggle.scripts.OnClick()
    assert(not p.screenshot:IsShown() and p.canvas:IsShown(), "interactive layout was removed")
    p.screenshotToggle.scripts.OnClick()
    p.screenshot.scripts.OnClick()
    w.next.scripts.OnClick()
    assert(not zoom:IsShown() and not p.screenshot:IsShown() and p.canvas:IsShown(), "modules show a stale screenshot")
    assert(not p.screenshotToggle:IsShown())
    w.next.scripts.OnClick()
    assert(p.canvas:IsShown(), "frame color selection lost its interactive preview")
    w.back.scripts.OnClick()
    w.back.scripts.OnClick()
    w.classic.scripts.OnClick()
    assert(not p.screenshot:IsShown() and p.canvas:IsShown(), "another preset shows Modern Dark art")
    w.modernDark.scripts.OnClick()
    UIParent:SetSize(640, 360)
    p.screenshot.scripts.OnClick()
    assert(zoom:GetWidth() <= 608 and zoom:GetHeight() <= 328, "zoom clips a small viewport")
    w:Hide()
    assert(not zoom:IsShown(), "closing setup orphaned the screenshot")
    assert(Suite.RootDB.installation.status == "pending", "preview changed installation state")
    assert(#H.reported == 0, table.concat(H.reported, "\n"))
end
print("Modern Dark screenshot, aspect, zoom, Escape registration, navigation and interactive colors passed")
