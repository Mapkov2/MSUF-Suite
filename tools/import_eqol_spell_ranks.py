"""Copy Enhance QoL's WoW Forever spell rank families into the cooldown manager.

Usage (from the repo root):
  python tools/import_eqol_spell_ranks.py <Enhance QoL folder> [--check]

<Enhance QoL folder> holds Enhance QoL's addon folders (its repository root or
the Forever client's Interface/AddOns); the tool reads
EnhanceQoL/Data/SpellRankData_Camelot.lua there. The file itself works too.

R41z0r (Enhance QoL) generates the families from the Forever client data
(scripts/generate_forever_spell_ranks.py in his repository) and permitted the
Suite to use them (2026-11-12). This tool only copies them: it reads his file,
checks every family (the key is its first rank, ranks are positive integers, no
rank in two families) and writes MSUF_Suite_CooldownManager/RankData.lua with
the source build in its header. --check compares instead of writing (exit 1 on
a difference). Update the file with this tool when Enhance QoL updates his.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "MSUF_Suite_CooldownManager" / "RankData.lua"
SOURCE = "EnhanceQoL/Data/SpellRankData_Camelot.lua"
BUILD = re.compile(r"^-- Forever build ([\d.]+)", re.M)
SECTION = re.compile(r"^\s*-- ([A-Z_]+)\s*$")
FAMILY = re.compile(r"^\s*\[(\d+)\] = \{ ([\d, ]+) \}, -- (.+?)\s*$")

HEADER = """local _, P = ...
local C = P.CDM
-- WoW Forever spell rank families: every rank of one spell, first rank first
-- (the family's identity), per class, then pet abilities.
-- Credits: R41z0r (Enhance QoL, https://www.curseforge.com/wow/addons/eqol)
-- built and maintains this list and allowed the Suite to use it. Copied from
-- EnhanceQoL/Data/SpellRankData_Camelot.lua, which he generates from the
-- Forever client data, build {build}.
-- Generated by tools/import_eqol_spell_ranks.py; do not edit by hand.
-- Read by EntryFill.lua (C.Ranks). Retail has no spell ranks and loads nothing here.
if not P.NS.Client.isForever then return end
C.RANK_FAMILIES = {{
"""


def parse(text):
    build = BUILD.search(text)
    if not build:
        raise ValueError("no '-- Forever build' line: is this Enhance QoL's SpellRankData_Camelot.lua?")
    body = text[text.index("SpellRankFamilies = {"):]
    lines, owner, count = [], {}, 0
    for raw in body.splitlines()[1:]:
        if raw.strip() == "}":
            break
        section = SECTION.match(raw)
        if section:
            lines.append("    -- " + section.group(1))
            continue
        family = FAMILY.match(raw)
        if not family:
            if raw.strip():
                raise ValueError("unexpected line: " + raw.strip())
            continue
        key, name = int(family.group(1)), family.group(3)
        ranks = [int(x) for x in family.group(2).split(",")]
        if ranks[0] != key:
            raise ValueError(f"family {key} ({name}) does not start with its key")
        for rank in ranks:
            if rank <= 0 or rank >= 2147483648:
                raise ValueError(f"family {key} ({name}): rank {rank} out of range")
            if rank in owner:
                raise ValueError(f"rank {rank} is in {owner[rank]} and {key}")
            owner[rank] = key
        lines.append("    [%d] = { %s }, -- %s" % (key, ", ".join(str(x) for x in ranks), name))
        count += 1
    if count == 0:
        raise ValueError("no families found")
    return build.group(1), lines, count


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source = Path(args[0])
    if source.is_dir():
        source = source / SOURCE
    build, lines, count = parse(source.read_text(encoding="utf-8"))
    text = HEADER.format(build=build) + "\n".join(lines) + "\n}\n"
    if "--check" in sys.argv:
        same = OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") == text
        print(("ok   " if same else "DIFF ") + f"{OUTPUT.name}: {count} families, Forever build {build}")
        return 0 if same else 1
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {count} families, Forever build {build}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
